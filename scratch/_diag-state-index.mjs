// 诊断：§5 决策表派生 29 条 vs 索引 28 条 —— 差的是哪一条？
import { readFileSync } from 'node:fs'
const m = await import('../scripts/prt/reachability.mjs')
const doc = readFileSync('docs/MULTI-AGENT-FEATURE-STATUS.md', 'utf8')
const derived = m.decisionStateRows(doc)
const index = m.decisionStateIndex(doc)
console.log('派生', derived.length, '条 | 索引', index.length, '条')
const idxNums = new Set(index.map((r) => String(r.n ?? r.number ?? r.id)))
const dvNums = new Set(derived.map((r) => String(r.n ?? r.number ?? r.id)))
console.log('\n索引里有、派生里没有：', JSON.stringify([...idxNums].filter((n) => !dvNums.has(n))))
console.log('派生里有、索引里没有：', JSON.stringify([...dvNums].filter((n) => !idxNums.has(n))))
console.log('\n派生每条的 n 与状态：')
for (const r of derived) console.log('  ', JSON.stringify({ n: r.n ?? r.number ?? r.id, status: r.status ?? r.state, 事项: String(r.title ?? r.item ?? '').slice(0, 40) }))
console.log('\n索引每条的 n：', JSON.stringify([...idxNums]))
console.log('\n违规：', JSON.stringify(m.decisionStateViolations(doc).slice(0, 5)))
