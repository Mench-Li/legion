/** 取某角色（岗位）的标准；未知角色用通用兜底。 */
export function standardsFor(role) {
  return STAGE_STANDARDS[role] ?? DEFAULT_STANDARD
}

/** 与默认内容是否全等（用于判断该任务是否"自带手写标准"）。 */
export function isDefaultFor(role, standard) {
  const d = standardsFor(role)
  return JSON.stringify(d.acceptance) === JSON.stringify(standard.acceptance)
    && JSON.stringify(d.do) === JSON.stringify(standard.do)
    && JSON.stringify(d.dont) === JSON.stringify(standard.dont)
}

