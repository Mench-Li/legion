/**
 * 军团阶段标准（stage-standards）：生成任务时**必须**同时生成的三件套——
 *   acceptance：验收标准（逐条可验证，交付方对照自检、将军对照验收）
 *   do    ：边界·做什么（scope in）
 *   dont  ：边界·不做什么（scope out）
 *
 * 消费方：team-hub server.mjs —— 发布目标生成阶段任务链 / POST /api/create 建任务时，
 * 若调用方没给验收标准/边界，就按任务的 role 套用本模板（未知 role 用 DEFAULT）。
 * 因此任何任务生成（含 AI 拆解出的子任务、手动建任务）都不再出现"空验收标准"。
 */
export const DEFAULT_STANDARD = {
  acceptance: [
    '产出与本阶段职责一致，能回答「为谁、解决什么、怎么验收」',
    '每条关键结论可验证：有真实依据（引用 / 命令输出 / 样例），不得虚构',
    '成果自检无常识性错误、无自相矛盾、无遗漏必答项',
    '以「交将军可验收」为完成口径：提交时按验收标准逐条说明对照结果',
  ],
  do: [
    '只做本任务阶段该做的事，改动与产物限制在该任务的工作目录内',
    '用证据说话：真实命令输出、文件路径、引用来源',
    '遇到超出职责范围或口径不清之处，明确提出而不是擅自扩大范围',
  ],
  dont: [
    '不越权执行其他阶段的职责（本角色之外的设计 / 实现 / 发布等）',
    '不虚构任何证据、不编造命令输出或数据',
    '不擅自 git push、发布上线，不改任务范围之外的文件',
  ],
}

